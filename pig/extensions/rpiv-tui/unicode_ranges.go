// inRanges reports whether r falls in one of the inclusive pairs of table.
func inRanges(table []rune, r rune) bool {
	lo, hi := 0, len(table)/2
	for lo < hi {
		mid := (lo + hi) / 2
		switch {
		case r < table[2*mid]:
			hi = mid
		case r > table[2*mid+1]:
			lo = mid + 1
		default:
			return true
		}
	}
	return false
}
